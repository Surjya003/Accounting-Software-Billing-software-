def get_contrast_text_color(hex_bg: str) -> str:
    """Returns FFFFFF or 000000 depending on background luminance for Excel cells."""
    h = hex_bg.lstrip("#")
    if len(h) != 6:
        return "FFFFFF"
    r = int(h[0:2], 16)
    g = int(h[2:4], 16)
    b = int(h[4:6], 16)
    luminance = (0.299 * r + 0.587 * g + 0.114 * b) / 255
    return "000000" if luminance > 0.55 else "FFFFFF"


# Number to Indian Words Helper
ONES = ["", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine", "Ten",
        "Eleven", "Twelve", "Thirteen", "Fourteen", "Fifteen", "Sixteen", "Seventeen", "Eighteen", "Nineteen"]
TENS = ["", "", "Twenty", "Thirty", "Forty", "Fifty", "Sixty", "Seventy", "Eighty", "Ninety"]

def num_to_words_inr(amount_float: float) -> str:
    """Converts number to Indian Rupee Words (Lakhs, Crores format)."""
    amount = Decimal(str(amount_float)).quantize(Decimal("0.01"))
    rupees = int(amount)
    paise = int((amount - rupees) * 100)
    
    if rupees == 0 and paise == 0:
        return "Zero Rupees Only"
        
    def convert_below_thousand(n: int) -> str:
        if n < 20:
            return ONES[n]
        elif n < 100:
            return TENS[n // 10] + (" " + ONES[n % 10] if n % 10 != 0 else "")
        else:
            return ONES[n // 100] + " Hundred" + (" " + convert_below_thousand(n % 100) if n % 100 != 0 else "")
            
    def convert_indian(n: int) -> str:
        if n == 0:
            return ""
        if n < 1000:
            return convert_below_thousand(n)
        elif n < 100000:
            return convert_indian(n // 1000) + " Thousand " + convert_below_thousand(n % 1000)
        elif n < 10000000:
            return convert_indian(n // 100000) + " Lakh " + convert_indian(n % 100000)
        else:
            return convert_indian(n // 10000000) + " Crore " + convert_indian(n % 10000000)

    words = "INR " + convert_indian(rupees).strip() + " Rupees"
    if paise > 0:
        words += " and " + convert_below_thousand(paise) + " Paise"
    words += " Only"
    return " ".join(words.split())


class NumberedCanvas(canvas.Canvas):
    """Canvas that adds page numbers and footer dynamically."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont(FONT_REGULAR, 8)
        self.setFillColor(colors.HexColor("#64748B"))
        
        # Draw bottom line across full page width (portrait or landscape)
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        page_w = self._pagesize[0]
        self.line(36, 30, page_w - 36, 30)
        
        # Footer text
        footer_text = f"Generated by {APP_NAME} on {datetime.now().strftime('%d-%m-%Y %H:%M')}"
        page_text = f"Page {self._pageNumber} of {page_count}"
        
        self.drawString(36, 18, footer_text)
        self.drawRightString(page_w - 36, 18, page_text)
        self.restoreState()


