_ICON_CACHE: Dict[str, QIcon] = {}


def get_pixmap(name: str, color: str = "#64748B", size: int = 20) -> QPixmap:
    """Generate a crisp QPixmap from SVG with specified color and size."""
    svg = SVG_ICONS.get(name, SVG_ICONS["info"])
    recolored = svg.replace("currentColor", color)
    renderer = QSvgRenderer(QByteArray(recolored.encode("utf-8")))

    # Render at 2x resolution for High-DPI sharpness
    scale = 2
    pix = QPixmap(size * scale, size * scale)
    pix.fill(Qt.transparent)
    painter = QPainter(pix)
    renderer.render(painter)
    painter.end()
    pix.setDevicePixelRatio(scale)
    return pix


def get_icon(name: str, color: Optional[str] = None, size: int = 20) -> QIcon:
    """
    Get a QIcon for a given icon name.
    If color is None, default slate color is used.
    Caches icons by (name, color, size).
    """
    if color is None:
        color = "#64748B"
    cache_key = f"{name}_{color}_{size}"
    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    pix = get_pixmap(name, color=color, size=size)
    icon = QIcon(pix)
    _ICON_CACHE[cache_key] = icon
    return icon


def clear_icon_cache() -> None:
    """Clear icon cache when theme changes."""
    _ICON_CACHE.clear()
